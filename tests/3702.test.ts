function longestSubsequence(nums: number[]): number {
    let n = nums.length;
    let left = 0;
    let removedCount = 0;
    let fullXor = nums.reduce((acc, curr) => acc ^ curr, 0);

    if (fullXor !== 0) {
        return n;
    }

    while (fullXor === 0 && left < n) {
        if ((fullXor ^ nums[left]) === 0) {
            left++;
        } else {
            fullXor = fullXor ^ nums[left];
            removedCount++;
        }
    }

    return fullXor !== 0 ? nums.length - removedCount : 0;
}
